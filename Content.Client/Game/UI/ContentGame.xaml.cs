using Content.Client.Chat;
using Content.Client.ConfigurationUI;
using Content.Client.UserInterface.Controls;
using Content.Shared.Input;
using Robust.Client.AutoGenerated;
using Robust.Client.Input;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;

namespace Content.Client.Game.UI;

[GenerateTypedNameReferences]
public sealed partial class ContentGame : UIScreen
{
    [Dependency] private ConfigurationUIManager _configuration = default!;
    [Dependency] private IInputManager _inputManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IUserInterfaceManager _userInterfaceManager = default!;

    private ChatSystem? _chatSystem;
    
    public ContentGame()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        
        ConfContainer.AddChild(_configuration.GetOrCreateContainer(new ConfigurationItem<bool>("transform_view_enabled", false)));
        ConfContainer.AddChild(_configuration.GetOrCreateContainer(new ConfigurationItem<bool>("pause_render", false)));
        ConfContainer.AddChild(_configuration.GetOrCreateContainer(new ConfigurationItem<bool>("render_shitty_skybox", true)));
        ConfContainer.AddChild(_configuration.GetOrCreateContainer(new ConfigurationItem<bool>("render_debug", false)));
        ConfContainer.AddChild(_configuration.GetOrCreateContainer(new ConfigurationItem<bool>("render_lighting", true)));

        ChatPanel.Visible = false;
        ChatInput.OnTextEntered += OnChatTextEntered;
        ChatInput.OnFocusExit += OnChatFocusExit;
    }

    protected override void OnLoaded()
    {
        base.OnLoaded();
        _inputManager.KeyBindStateChanged += InputManagerOnKeyBindStateChanged;
    }

    protected override void OnUnloaded()
    {
        _inputManager.KeyBindStateChanged -= InputManagerOnKeyBindStateChanged;
        base.OnUnloaded();
    }

    private void InputManagerOnKeyBindStateChanged(ViewportBoundKeyEventArgs args)
    {
        var keyEvent = args.KeyEventArgs;

        if (keyEvent.Function != ContentKeyFunctions.ChatFocusAction ||
            keyEvent.State != BoundKeyState.Up ||
            _userInterfaceManager.KeyboardFocused != null)
        {
            return;
        }

        ChatPanel.Visible = true;
        ChatInput.Clear();
        ChatInput.GrabKeyboardFocus();
        keyEvent.Handle();
    }

    private void OnChatTextEntered(LineEdit.LineEditEventArgs args)
    {
        _chatSystem ??= _entityManager.System<ChatSystem>();
        _chatSystem.SendMessage(args.Text);
        ChatInput.ReleaseKeyboardFocus();
    }

    private void OnChatFocusExit(LineEdit.LineEditEventArgs args)
    {
        ChatInput.Clear();
        ChatPanel.Visible = false;
    }
}